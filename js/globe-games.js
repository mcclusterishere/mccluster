/* GAMES ON THE GLOBE (owner, 2026-11-03: a new "Games" tab on the globe, its own overlay like the data layers; experimental,
   the house owner's only for now). Drill down country → state → town, then see that town's storylines (which run on
   repeat: what is playing now and next) and its missions, and start one.

   The data is data/games/world.v1.json, generated by tools/publish-games-world.mjs from the universe registry
   (docs/universe/universe-registry.json → gamesWorld) and the story sources it names. Nothing is fetched until the overlay
   opens, and js/action-globe.js only offers it when the server's owner answer says so (isOwner: /v1/world/access).
   Every destination keeps its own gate: opening one here grants nothing.

   The schedule math is pure and exported for the tests (scripts/test/games-world.test.mjs). */
(function (root) {
  'use strict';

  /* ---------- the schedule: a storyline loops from its epoch over its ordered scene durations ---------- */
  function scheduleAt(storyline, t) {
    const scenes = storyline && storyline.scenes || [];
    const epoch = Date.parse(storyline && storyline.loop && storyline.loop.epoch);
    const period = storyline && storyline.loop && storyline.loop.periodMs;
    if (!scenes.length || !Number.isFinite(epoch) || !(period > 0) || !Number.isFinite(t)) return null;
    const into = (((t - epoch) % period) + period) % period;
    const loopStart = t - into;
    let i = scenes.length - 1;
    for (let n = 0; n < scenes.length; n++) { if (into < scenes[n].offsetMs + scenes[n].durationMs) { i = n; break; } }
    const now = scenes[i], j = (i + 1) % scenes.length, next = scenes[j];
    const startsAt = loopStart + now.offsetMs, endsAt = startsAt + now.durationMs;
    return {
      now: { index: i, scene: now, startsAt, endsAt, remainingMs: endsAt - t },
      next: { index: j, scene: next, startsAt: endsAt },
      loop: Math.floor((t - epoch) / period)
    };
  }

  function townPath(c, s, t) { return [c.id, s.id, t.id].join('/'); }
  function findTown(world, path) {
    const [ci, si, ti] = String(path || '').split('/');
    const c = (world.countries || []).find((x) => x.id === ci);
    const s = c && c.states.find((x) => x.id === si);
    const t = s && s.towns.find((x) => x.id === ti);
    return t ? { country: c, state: s, town: t } : null;
  }
  function townStorylines(world, path) {
    return (world.storylines || []).filter((s) => s.town === path);
  }
  /* every route a town offers: its destinations, its storylines' start routes and each scene's own route */
  function routes(world) {
    const out = [];
    for (const c of world.countries || []) for (const s of c.states) for (const t of s.towns) for (const e of t.entries) out.push(e.route);
    for (const s of world.storylines || []) { out.push(s.start); for (const x of s.scenes) if (x.route) out.push(x.route); }
    return out;
  }

  /* ---------- the panel ---------- */
  const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const clock = (ms) => new Date(ms).toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' });
  const mins = (ms) => { const m = Math.max(1, Math.round(ms / 60000)); return m >= 60 ? Math.floor(m / 60) + ' h ' + (m % 60) + ' min' : m + ' min'; };
  const KIND = { place: 'Place', story: 'Story', mission: 'Mission' };

  function mount(opts) {
    const o = Object.assign({ dataUrl: 'data/games/world.v1.json', now: () => Date.now(), onFly: null, target: '', parent: document.body }, opts || {});
    let world = null, loading = null, path = [], timer = 0;
    const el = document.createElement('section');
    el.id = 'gamesSheet'; el.className = 'games-sheet'; el.hidden = true;
    el.setAttribute('role', 'dialog'); el.setAttribute('aria-modal', 'false'); el.setAttribute('aria-labelledby', 'gamesTitle');
    el.innerHTML = '<div class="games-head"><button type="button" class="games-back" aria-label="Back" hidden>←</button>' +
      '<div class="games-heading"><small class="games-crumb" id="gamesCrumb">Games · experimental</small><h2 id="gamesTitle">Games</h2></div>' +
      '<button type="button" class="games-close" aria-label="Close Games">×</button></div><div class="games-body" id="gamesBody"></div>';
    o.parent.appendChild(el);
    const body = el.querySelector('.games-body'), title = el.querySelector('h2'), crumb = el.querySelector('.games-crumb'), back = el.querySelector('.games-back');
    const tgt = o.target ? ' target="' + esc(o.target) + '"' : '';

    function load() {
      if (world) return Promise.resolve(world);
      if (!loading) loading = fetch(o.dataUrl, { cache: 'no-cache' }).then((r) => { if (!r.ok) throw Error('games ' + r.status); return r.json(); })
        .then((d) => { world = d; return d; }, (e) => { loading = null; throw e; });
      return loading;
    }
    function list(items) { return '<ul class="games-list" role="list">' + items.join('') + '</ul>'; }
    function pick(kind, id, label, sub) {
      return '<li><button type="button" class="games-pick" data-' + kind + '="' + esc(id) + '"><span>' + esc(label) + '</span>' + (sub ? '<small>' + esc(sub) + '</small>' : '') + '<i aria-hidden="true">›</i></button></li>';
    }
    function storyCard(s) {
      const at = scheduleAt(s, o.now());
      if (!at) return '';
      const n = at.now.scene, x = at.next.scene, start = n.route || s.start;
      const where = (sc) => sc.anchor && (sc.anchor.place || sc.anchor.device || sc.anchor.equipment || sc.anchor.door) || '';
      return '<li class="games-story" data-storyline="' + esc(s.id) + '"><div class="games-story__top"><b>' + esc(s.title) + '</b><span class="games-live">Now playing</span></div>' +
        '<p class="games-now"><strong>' + esc((n.act ? 'Act ' + n.act + ' · ' : n.chapter ? n.chapter + ' · ' : '') + n.title) + '</strong>' + (where(n) ? ' <span>· ' + esc(where(n)) + '</span>' : '') + '</p>' +
        (n.summary ? '<p class="games-sum">' + esc(n.summary) + '</p>' : '') +
        '<p class="games-next">Until ' + esc(clock(at.now.endsAt)) + ' · then <b>' + esc(x.title) + '</b> in ' + esc(mins(at.now.remainingMs)) + '</p>' +
        '<details class="games-scenes"><summary>All ' + s.scenes.length + ' scenes · repeats every ' + esc(mins(s.loop.periodMs)) + '</summary><ol>' +
        s.scenes.map((sc, i) => '<li' + (i === at.now.index ? ' aria-current="true"' : '') + '>' + esc(sc.title) + (where(sc) ? ' <small>' + esc(where(sc)) + '</small>' : '') + '</li>').join('') + '</ol></details>' +
        '<a class="games-start" data-start="' + esc(s.id) + '" href="' + esc(start) + '"' + tgt + '>Start ' + esc(s.title) + ' →</a></li>';
    }
    function entryRow(e) {
      return '<li class="games-entry" data-entry="' + esc(e.id) + '"><div><span class="games-tag">' + esc(KIND[e.kind] || e.kind) + '</span><b>' + esc(e.title) + '</b>' +
        (e.character ? '<small>' + esc(e.character) + '</small>' : '') + '<p>' + esc(e.blurb && e.blurb.text) + '</p></div>' +
        '<a class="games-start" href="' + esc(e.route) + '"' + tgt + '>Start →</a></li>';
    }
    function render() {
      clearInterval(timer); timer = 0;
      back.hidden = path.length === 0;
      if (!world) { title.textContent = 'Games'; body.innerHTML = '<p class="games-msg">Loading…</p>'; return; }
      const c = path[0] && world.countries.find((x) => x.id === path[0]);
      const s = c && path[1] && c.states.find((x) => x.id === path[1]);
      const t = s && path[2] && s.towns.find((x) => x.id === path[2]);
      crumb.textContent = ['Games', c && c.name, s && s.name].filter(Boolean).join(' · ');
      if (t) {
        const p = townPath(c, s, t), stories = townStorylines(world, p);
        title.textContent = t.name;
        const hoods = new Map((t.neighborhoods || []).map((n) => [n.id, n]));
        const groups = [];
        for (const e of t.entries) { const k = e.neighborhood || ''; let g = groups.find((x) => x.k === k); if (!g) groups.push(g = { k, items: [] }); g.items.push(e); }
        body.innerHTML = (stories.length ? '<h3>Storylines</h3><ul class="games-list" role="list">' + stories.map(storyCard).join('') + '</ul>' : '') +
          '<h3>' + (stories.length ? 'Missions and places' : 'Missions') + '</h3>' +
          groups.map((g) => (hoods.get(g.k) ? '<h4>' + esc(hoods.get(g.k).name) + '</h4>' : '') + '<ul class="games-list" role="list">' + g.items.map(entryRow).join('') + '</ul>').join('');
        if (stories.length) timer = setInterval(() => { if (!el.hidden) render(); }, 30000);
        return;
      }
      if (s) { title.textContent = s.name; body.innerHTML = list(s.towns.map((x) => pick('town', x.id, x.name, x.entries.length + (x.entries.length === 1 ? ' mission' : ' missions') + (townStorylines(world, townPath(c, s, x)).length ? ' · storylines' : '')))); return; }
      if (c) { title.textContent = c.name; body.innerHTML = list(c.states.map((x) => pick('state', x.id, x.name, x.towns.map((y) => y.name).join(', ')))); return; }
      title.textContent = 'Choose a country';
      body.innerHTML = list(world.countries.map((x) => pick('country', x.id, x.name, x.region)));
    }
    function go(next) {
      path = next.slice(0, 3); render();
      if (path.length === 3 && world && typeof o.onFly === 'function') { const f = findTown(world, path.join('/')); if (f) o.onFly(f.town.lat, f.town.lon, f.town.name); }
      body.scrollTop = 0;
    }
    el.addEventListener('click', (e) => {
      const b = e.target.closest && e.target.closest('[data-country],[data-state],[data-town]');
      if (b) { const d = b.dataset; go(d.country ? [d.country] : d.state ? [path[0], d.state] : [path[0], path[1], d.town]); }
    });
    back.onclick = () => go(path.slice(0, -1));
    el.querySelector('.games-close').onclick = () => close();
    el.addEventListener('keydown', (e) => { if (e.key === 'Escape') close(); });
    function open(start) {
      el.hidden = false; render();
      return load().then(() => { const want = start && findTown(world, start) ? String(start).split('/') : path; go(want); return true; },
        () => { body.innerHTML = '<p class="games-msg">The games list could not load. Try again shortly.</p>'; return false; });
    }
    function close() { el.hidden = true; clearInterval(timer); timer = 0; if (typeof o.onClose === 'function') o.onClose(); }
    return { open, close, isOpen: () => !el.hidden, element: el, path: () => path.join('/') };
  }

  root.HuGames = Object.freeze({ scheduleAt, findTown, townStorylines, routes, mount });
})(typeof window === 'undefined' ? globalThis : window);
