// Render a reviewed, pending-only seed. This command never connects to a database.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../../', import.meta.url);
const input = new URL('docs/control-plane/admin-evidence-20261020/funding-register.json', root);
const output = new URL('supabase/pending/20261020193357_funding_criteria_register_v1.sql', root);
const data = JSON.parse(await readFile(input, 'utf8'));
if (data.schema_version !== 1 || data.opportunities.length !== 72 ||
    new Set(data.opportunities.map(r => r.opportunity_id)).size !== 72 ||
    new Set(data.opportunities.map(r => r.criteria_register.route_id)).size !== 72) throw Error('Invalid 72-route register');
const q = value => "'" + String(value).replaceAll("'", "''") + "'";
const values = data.opportunities.map(r => '(' + [r.opportunity_id, r.funder_name, r.program_title,
  r.source_kind, r.availability, r.source_url, r.eligibility_note, r.reviewed_at].map(q).join(',') + ',' +
  q(JSON.stringify(r.criteria_register)) + '::jsonb)').join(',\n');
const sql = `-- PENDING REVIEW ONLY. Generated by node scripts/funding/render-register-seed.mjs.
-- Existing authority: public.action_funding_opportunities (20261016020407).
-- One metadata column, no new table/role/grant. No applicant, award, payout or publication.
-- Source retrieval does not establish eligibility. Existing human-reviewed registers
-- are never overwritten; future amendments require a separate reviewed change.
begin;
alter table public.action_funding_opportunities
  add column if not exists criteria_register jsonb;
comment on column public.action_funding_opportunities.criteria_register is
  'Versioned public program criteria and source metadata only. No confidential applicant documents or automatic eligibility authority.';
alter table public.action_funding_opportunities
  drop constraint if exists action_funding_criteria_register_object;
alter table public.action_funding_opportunities
  add constraint action_funding_criteria_register_object
  check (criteria_register is null or (jsonb_typeof(criteria_register) = 'object' and coalesce(criteria_register->>'schema_version' = '1', false)));
insert into public.action_funding_opportunities as prior
  (opportunity_id,funder_name,program_title,source_kind,availability,source_url,eligibility_note,reviewed_at,criteria_register)
values
${values}
on conflict (opportunity_id) do update
set criteria_register = excluded.criteria_register || jsonb_build_object(
      'previous_catalog_record', jsonb_build_object('source_url',prior.source_url,
        'eligibility_note',prior.eligibility_note,'availability',prior.availability,'reviewed_at',prior.reviewed_at)),
    eligibility_note = excluded.eligibility_note
where prior.criteria_register is null;
commit;
`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== sql) throw Error('Pending seed differs; rerun renderer');
  console.log('72-route pending seed is current');
} else {
  await writeFile(output, sql);
  console.log(fileURLToPath(output));
}
