#!/usr/bin/env node
// A forward correction over the frozen, already-applied catalog. Never regenerate the seven imports.
// node tools/build-drawdown-credit-fallback.mjs [--check]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readCatalog, validateCatalog, detailsRow, CC_BY } from './build-mission-import.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const POLICY_PATH = 'data/missions/drawdown/publication-policy.json';
export const STAGE_NAME = '20261120050000_action_mission_drawdown_credit_fallback.sql';
export const HASH_FIELDS = Object.freeze(['credit_line', 'about', 'about_credit', 'source_url', 'license_name', 'license_url', 'doi']);
const sha256 = (s) => createHash('sha256').update(s).digest('hex');
const lit = (s) => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const oldPrefix = (url) => `Solution summary from Project Drawdown (${url}), used with permission`;
const newPrefix = (url) => `Solution listed in Project Drawdown's Explorer (${url})`;
export const fingerprint = (d) => createHash('md5').update(HASH_FIELDS.map((k) => d[k] ?? '').join('\u001f')).digest('hex');
export const readPolicy = (root = ROOT) => JSON.parse(readFileSync(join(root, POLICY_PATH), 'utf8'));

/** The only released fields that change: the website quote, its credit and the unsupported permission prefix. */
export function publicationDetails(m) {
  const d = detailsRow(m);
  if (d.about == null) return d;
  const before = oldPrefix(d.source_url);
  if (!d.credit_line.startsWith(before)) throw new Error(`${m.slug}: unexpected historical credit prefix`);
  return { ...d, credit_line: newPrefix(d.source_url) + d.credit_line.slice(before.length), about: null, about_credit: null };
}

export function prepare(input = readCatalog(), policy = readPolicy()) {
  const errors = validateCatalog(input.catalog);
  if (errors.length) throw new Error(errors.join('\n'));
  if (sha256(input.text) !== policy.historical_catalog_sha256) throw new Error('The applied catalog is frozen; use a new migration for a later change.');
  if (policy.schema !== 'mccluster.mission-publication-policy/v1' || policy.catalog !== 'drawdown'
      || policy.permission_evidence !== 'not_verified' || policy.public_website_excerpts !== false || policy.source_page_state !== 'draft') {
    throw new Error('This correction removes unverified website content and does not attest source-page permission.');
  }
  const missions = input.catalog.missions;
  const targets = missions.filter((m) => m.about != null).map((m) => {
    const before = detailsRow(m), after = publicationDetails(m);
    return { id: before.mission_id, before, after, beforeHash: fingerprint(before), afterHash: fingerprint(after) };
  }).sort((a, b) => a.id.localeCompare(b.id));
  if (missions.length !== policy.mission_count || targets.length !== policy.website_excerpt_count
      || missions.filter((m) => m.source.license === CC_BY.name).length !== policy.assessment_citation_count
      || policy.mission_count !== 125 || policy.website_excerpt_count !== 87 || policy.assessment_citation_count !== 43) {
    throw new Error('The frozen 125 missions, 87 website excerpts and 43 assessment citations must match.');
  }
  for (const m of missions) {
    const d = publicationDetails(m);
    if (d.about != null || d.about_credit != null || /used with permission/i.test(d.credit_line)) throw new Error(`${m.slug}: unsupported public content remains`);
  }
  if (!/^supabase\/(pending|migrations)\/\d{14}_action_mission_drawdown_credit_fallback\.sql$/.test(policy.forward_file)
      || JSON.stringify(policy.rollback_files) !== JSON.stringify([1, 2].map((i) => `supabase/pending/20261120050000_action_mission_drawdown_credit_fallback_0${i}.rollback.sql`))) {
    throw new Error('Unexpected forward or recovery artifact path.');
  }
  return { policy, targets };
}

const hashSql = (row) => `md5(${HASH_FIELDS.map((k) => `coalesce(${row}.${k}, '')`).join(' || chr(31) || ')})`;
const permissionClaim = "position('used with permission' in lower(d.credit_line)) > 0";

function render({ policy, targets }, rollback, part = 0) {
  const chosen = rollback ? targets.slice(part * 44, (part + 1) * 44) : targets;
  const expectedColumns = rollback ? 'id, before_md5, after_md5, original_about' : 'id, before_md5, after_md5';
  const values = chosen.map((t) => `    (${lit(t.id)}::uuid, ${lit(t.beforeHash)}, ${lit(t.afterHash)}${rollback ? `, ${lit(t.before.about)}` : ''})`).join(',\n');
  const heading = rollback ? `RECOVERY ONLY, PART ${part + 1} OF 2` : 'REMOVE UNVERIFIED WEBSITE EXCERPTS BEFORE PUBLICATION';
  return `-- DRAWDOWN MISSION CREDITS: ${heading}
-- Generated by tools/build-drawdown-credit-fallback.mjs from the frozen missions.json
-- (sha256 ${policy.historical_catalog_sha256}) and publication-policy.json.
-- Check with node tools/build-drawdown-credit-fallback.mjs --check. Applied SQL bytes never change.
--
-- ${rollback ? 'RECOVERY ARTIFACT. Never a forward migration. Restore only after the publication is rolled back.' : 'PENDING. Apply after the seven recorded imports and BEFORE action_mission_drawdown_publish.'}
-- Apply this exact file with Supabase MCP apply_migration (it runs as postgres), then record its actual version.
-- ${rollback ? 'Recovery requires separate authorization and verified permission before any later republication.' : 'Migration name: action_mission_drawdown_credit_fallback. Permission evidence was not verified on 2026-11-20.'}
-- ${rollback ? 'Both recovery parts are required to restore all 87 historical detail rows. They may run in either order.' : 'The original 125 missions stay unchanged. All 43 CC BY assessment citations, creators, titles, DOI and license links stay.'}
-- ${rollback ? 'Each part refuses unless all 125 Drawdown missions are drafts; no quotation is restored into a public mission.' : 'Only 87 details rows change: about/about_credit become NULL; credit_line identifies the Explorer page without a permission claim.'}
-- ${rollback ? 'The stored excerpts are historical recovery material, not permission evidence.' : 'The website excerpts are separate from the CC BY assessment spreadsheets. This does not publish the source page.'}
-- Exact before/after fingerprints reject concurrent or unexpected credit/source/license edits (55000); reruns do nothing.
-- No schema, grants, policies, original mission wording, proof hints, safety notes or assignments change.
-- Rollback files: ${policy.rollback_files.map((p) => p.split('/').at(-1)).join(', ')}.
-- Proof: scripts/test/drawdown-credit-fallback.integration.mjs (isolated PostgreSQL), plus the root contract tests.
begin;
set local lock_timeout = '5s';
set local standard_conforming_strings = on;

do $drawdown_credit_fallback$
declare
  expected record;
  actual record;
  actual_md5 text;
  before_prefix text;
  after_prefix text;
begin
  -- Lock the existing catalog and missions in a stable order, including the 38 detail rows we preserve.
  perform d.mission_id from public.action_mission_details d
    join public.action_missions m on m.id = d.mission_id
    where d.catalog = 'drawdown' order by d.mission_id for update of d, m;
  if (select count(*) from public.action_mission_details d join public.action_missions m on m.id = d.mission_id
      where d.catalog = 'drawdown') <> 125 then
    raise exception 'Drawdown credit correction refused: expected all 125 imported missions and details' using errcode = '55000';
  end if;
  if exists (select 1 from public.action_mission_details d join public.action_missions m on m.id = d.mission_id
      where d.catalog = 'drawdown' and m.status <> 'draft'${rollback ? '' : ` and (d.about is not null or d.about_credit is not null or ${permissionClaim})`}) then
    raise exception '${rollback ? 'Drawdown credit recovery refused: all 125 missions must be drafts' : 'Drawdown credit correction refused: remove the publication before changing unverified public excerpts'}' using errcode = '55000';
  end if;

  for expected in select * from (values
${values}
  ) as v(${expectedColumns}) order by id loop
    select d.* into actual from public.action_mission_details d
      where d.mission_id = expected.id and d.catalog = 'drawdown';
    if not found then
      raise exception 'Drawdown credit correction refused: missing target %', expected.id using errcode = '55000';
    end if;
    actual_md5 := ${hashSql('actual')};
    if actual_md5 = expected.${rollback ? 'before_md5' : 'after_md5'} then continue; end if;
    if actual_md5 <> expected.${rollback ? 'after_md5' : 'before_md5'} then
      raise exception 'Drawdown credit correction refused: credit or source changed for %', expected.id using errcode = '55000';
    end if;
    before_prefix := 'Solution summary from Project Drawdown (' || actual.source_url || '), used with permission';
    after_prefix := 'Solution listed in Project Drawdown''s Explorer (' || actual.source_url || ')';
    if left(actual.credit_line, length(${rollback ? 'after_prefix' : 'before_prefix'})) <> ${rollback ? 'after_prefix' : 'before_prefix'} then
      raise exception 'Drawdown credit correction refused: unexpected credit prefix for %', expected.id using errcode = '55000';
    end if;
    update public.action_mission_details
      set credit_line = ${rollback ? 'before_prefix || substr(actual.credit_line, length(after_prefix) + 1)' : 'after_prefix || substr(actual.credit_line, length(before_prefix) + 1)'},
          about = ${rollback ? 'expected.original_about' : 'null'},
          about_credit = ${rollback ? "'Solution summary © Project Drawdown, used with permission.'" : 'null'},
          updated_at = now()
      where mission_id = expected.id;
    select ${hashSql('d')} into actual_md5 from public.action_mission_details d where d.mission_id = expected.id;
    if actual_md5 <> expected.${rollback ? 'before_md5' : 'after_md5'} then
      raise exception 'Drawdown credit correction refused: resulting fingerprint differs for %', expected.id using errcode = '55000';
    end if;
  end loop;
${rollback ? '' : `
  if exists (select 1 from public.action_mission_details d where d.catalog = 'drawdown'
      and (d.about is not null or d.about_credit is not null or ${permissionClaim})) then
    raise exception 'Drawdown credit correction refused: unexpected website content remains' using errcode = '55000';
  end if;
`}
end
$drawdown_credit_fallback$;

commit;
`;
}

export function buildFiles(input = readCatalog(), policy = readPolicy()) {
  const prepared = prepare(input, policy);
  const files = { [policy.forward_file]: render(prepared, false) };
  policy.rollback_files.forEach((file, i) => { files[file] = render(prepared, true, i); });
  for (const [file, sql] of Object.entries(files)) if (Buffer.byteLength(sql, 'utf8') > 32000) throw new Error(`${file} exceeds one migration call's 32000-byte bound`);
  return files;
}

function main() {
  const files = buildFiles();
  const changed = Object.entries(files).filter(([file, sql]) => !existsSync(join(ROOT, file)) || readFileSync(join(ROOT, file), 'utf8') !== sql);
  if (process.argv.includes('--check')) {
    if (changed.length) throw new Error(`Drawdown credit artifacts drifted:\n${changed.map(([file]) => file).join('\n')}`);
    console.log('Drawdown credit correction and two recovery files match the frozen catalog.');
    return;
  }
  if (changed.some(([file]) => file.startsWith('supabase/migrations/'))) throw new Error('Applied correction bytes must not change.');
  for (const [file, sql] of changed) writeFileSync(join(ROOT, file), sql);
  console.log(`Drawdown credit artifacts current (${files ? Object.keys(files).length : 0} files).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { main(); } catch (e) { console.error(e.message); process.exitCode = 1; }
}
