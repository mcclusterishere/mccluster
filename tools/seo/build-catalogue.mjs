#!/usr/bin/env node
/* THE CATALOGUE AS HTML AND AS A MUSIC GRAPH.

     node tools/seo/build-catalogue.mjs          # rewrite the blocks
     node tools/seo/build-catalogue.mjs --check  # fail if they drifted

   catalogue.html used to arrive empty and fill itself from
   data/catalogue.json with a script. A browser saw the registry; a crawler
   that does not run scripts, and most AI crawlers do not, saw "Loading the
   registry...". This writes the same rows into the page as real HTML (the
   script still runs and repaints them identically), and writes the
   MusicAlbum / MusicRecording graph beside it, each recording at a stable
   address: catalogue.html#<slug>.

   CREDITS ARE CLAIMS, so they are made only where the site states them:
   - byArtist is Matthew McCluster only where nothing on the site credits
     anybody else ("Written & performed by Matthew McCluster unless credited
     otherwise").
   - "Money or the Power" is credited on docket-516.html to Old Jay ft. Ocho
     (prod. Pax), so it is Old Jay's, not his.
   - "Dealer Plates" is "Prod. Zakir & McCluster": a producer credit, not an
     artist credit.
   - "Upset" names three other artists and no role for him: no artist claim.
   - CIA Mind Control is published under an alias, and one of its titles is
     gated on purpose. The album is listed, with no artist and no track
     list; gated titles are never written into the static page or the
     graph. The owner decides how that record is credited in public. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SITE = "https://matthew.mccluster.org";
const PAGE = join(ROOT, "catalogue.html");
const PERSON = { "@id": `${SITE}/#matthew-mccluster` };
const MARK = {
  ld: ["<!-- catalogue-graph:start (generated by tools/seo/build-catalogue.mjs; do not edit by hand) -->", "<!-- catalogue-graph:end -->"],
  shelf: ["<!-- catalogue-shelf:start (generated) -->", "<!-- catalogue-shelf:end -->"],
  reg: ["<!-- catalogue-registry:start (generated) -->", "<!-- catalogue-registry:end -->"]
};

const esc = (s) => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;")
  .replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

export function isoDuration(len) {
  const m = /^(\d+):(\d{2})$/.exec(String(len || "").trim());
  return m ? `PT${+m[1]}M${+m[2]}S` : undefined;
}

/* who made it, as far as the site actually says */
const CREDIT = {
  "money-or-the-power": { byArtist: { "@type": "MusicGroup", name: "Old Jay" } },
  "dealer-plates": { producer: [PERSON, { "@type": "Person", name: "Zakir" }] },
  "dealer-plates-b": { producer: [PERSON, { "@type": "Person", name: "Zakir" }] },
  "upset": {}
};
const NO_GRAPH_ALBUMS = new Set(["cia-mind-control"]);

function creditFor(t) {
  if (CREDIT[t.slug]) return CREDIT[t.slug];
  return { byArtist: PERSON };
}

export function recordings(cat) {
  return (cat.tracks || [])
    .filter((t) => !t.gated && !NO_GRAPH_ALBUMS.has(t.albumSlug))
    .map((t) => JSON.parse(JSON.stringify({
      "@type": "MusicRecording",
      "@id": `${SITE}/catalogue.html#${t.slug}`,
      url: `${SITE}/catalogue.html#${t.slug}`,
      name: t.title,
      isrcCode: t.isrc || undefined,
      duration: isoDuration(t.length),
      description: t.credit || undefined,
      inAlbum: t.album && slugOfAlbumName(t.album) !== "singles" ? { "@id": albumId(t) } : undefined,
      ...creditFor(t)
    })));
}

function slugOfAlbumName(name) {
  return String(name || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}
function albumId(t) {
  const slug = t.albumSlug || slugOfAlbumName(t.album);
  return slug === "here" ? `${SITE}/#album` : `${SITE}/catalogue.html#album-${slug}`;
}

export function buildGraph(cat, albums) {
  const recs = recordings(cat);
  const albumNodes = (albums.albums || []).filter((a) => a.slug !== "singles").map((a) => {
    const id = a.slug === "here" ? `${SITE}/#album` : `${SITE}/catalogue.html#album-${a.slug}`;
    const mine = recs.filter((r) => r.inAlbum && r.inAlbum["@id"] === id);
    const node = {
      "@type": "MusicAlbum",
      "@id": id,
      name: a.name,
      url: `${SITE}/album.html${a.slug === "here" ? "" : "?album=" + a.slug}`,
      image: `${SITE}/${a.art}`
    };
    if (NO_GRAPH_ALBUMS.has(a.slug)) {
      node.subjectOf = { "@type": "WebPage", url: `${SITE}/end-racism.html` };
      return node;
    }
    if (a.slug === "here") {
      Object.assign(node, { byArtist: PERSON, albumProductionType: "https://schema.org/StudioAlbum", albumReleaseType: "https://schema.org/AlbumRelease", datePublished: "2026" });
    }
    if (a.slug === "heal-the-3") {
      node.byArtist = [PERSON, { "@type": "MusicGroup", name: "VVS Madè" }];
      node.albumReleaseType = "https://schema.org/EPRelease";
    }
    if (a.slug === "equity-uprise") node.subjectOf = { "@type": "WebPage", url: `${SITE}/docket-516.html` };
    if (mine.length) {
      node.numTracks = mine.length;
      node.track = { "@type": "ItemList", numberOfItems: mine.length,
        itemListElement: mine.map((r, i) => ({ "@type": "ListItem", position: i + 1, item: { "@id": r["@id"] } })) };
    }
    return node;
  });
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "CollectionPage",
        "@id": `${SITE}/catalogue.html`,
        url: `${SITE}/catalogue.html`,
        name: "The McCluster catalogue: every registered recording",
        description: `The registered discography under ISRC prefix ${cat.isrc_prefix || "QT6KV"}, McCluster Corp's registrant code.`,
        isPartOf: { "@id": `${SITE}/#website` },
        about: PERSON,
        mainEntity: { "@type": "ItemList", numberOfItems: recs.length, itemListElement: recs.map((r, i) => ({ "@type": "ListItem", position: i + 1, item: { "@id": r["@id"] } })) }
      },
      { "@type": "Person", "@id": `${SITE}/#matthew-mccluster`, name: "Matthew McCluster", url: `${SITE}/matthew-mccluster.html` },
      ...albumNodes,
      ...recs
    ]
  };
}

/* the same markup the page's own script writes, plus an id per row */
export function registryRows(cat) {
  return (cat.tracks || []).filter((t) => !t.gated).map((t) => {
    const here = (t.albumSlug || "") === "here";
    const no = `${cat.isrc_prefix || "QT6KV"}·${String(t.no || t.order || "00").padStart(2, "0")}`;
    return `<li id="${esc(t.slug)}"><span class='no'>${esc(no)}</span><span class='t'>${here ? `<a href='album.html'>${esc(t.title)}</a>` : esc(t.title)}${t.credit ? `<small>${esc(t.credit)}</small>` : ""}</span><span class='al'>${esc(t.album || "")}</span></li>`;
  }).join("\n      ");
}

export function shelfLinks(albums) {
  return (albums.albums || []).map((a) =>
    `<a href="album.html?album=${esc(a.slug)}" data-cta="shelf-${esc(a.slug)}"><img class="cov" src="${esc(a.art)}" alt="" loading="lazy"><b>${esc(a.name)}</b><small>${a.tracks.length}${a.tracks.length === 1 ? " track" : " tracks"}</small></a>`
  ).join("\n      ");
}

function swap(html, [a, b], body) {
  const i = html.indexOf(a), j = html.indexOf(b);
  if (i < 0 || j < 0) throw new Error(`catalogue.html is missing the marker ${a}`);
  return html.slice(0, i + a.length) + "\n" + body + "\n      " + html.slice(j);
}

function main() {
  const cat = JSON.parse(readFileSync(join(ROOT, "data/catalogue.json"), "utf8"));
  const albums = JSON.parse(readFileSync(join(ROOT, "data/albums.json"), "utf8"));
  const html = readFileSync(PAGE, "utf8");
  let next = swap(html, MARK.ld, `  <script type="application/ld+json">${JSON.stringify(buildGraph(cat, albums))}</script>`);
  next = swap(next, MARK.shelf, "      " + shelfLinks(albums));
  next = swap(next, MARK.reg, "      " + registryRows(cat));
  if (process.argv.includes("--check")) {
    if (next !== html) { console.error("catalogue.html drifted from data/catalogue.json: run node tools/seo/build-catalogue.mjs"); process.exit(1); }
    console.log("catalogue: current");
    return;
  }
  writeFileSync(PAGE, next);
  console.log(`catalogue: wrote ${recordings(cat).length} recordings to catalogue.html`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
