#!/usr/bin/env node
/* THE PROFILE PAGE'S STRUCTURED DATA, GENERATED FROM ONE FILE.

     node tools/seo/build-entity-jsonld.mjs          # rewrite the block
     node tools/seo/build-entity-jsonld.mjs --check  # fail if it drifted

   data/entity-graph.json defines Matthew McCluster, McCluster Corp and the
   projects once. matthew-mccluster.html is the page that entity graph is
   about (its ProfilePage), so its JSON-LD is written from that file and
   nowhere else: the block between the entity-graph markers is replaced
   wholesale. Hand edits inside the markers are overwritten on the next
   run, and the SEO contract test runs --check so a hand edit that was not
   carried back into the data file fails CI instead of drifting.

   Why a ProfilePage separate from the Person: Google's ProfilePage
   documentation wants the page and the person as two things, the page
   pointing at the person through mainEntity. The page used to be typed
   ["Person", "ProfilePage"] in one node, which says one object is both a
   human being and a web page. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PAGE = join(ROOT, "matthew-mccluster.html");
const START = "<!-- entity-graph:start (generated by tools/seo/build-entity-jsonld.mjs from data/entity-graph.json; do not edit by hand) -->";
const END = "<!-- entity-graph:end -->";

export function buildGraph(g) {
  const { ids } = g;
  const profile = {
    "@type": "ProfilePage",
    "@id": ids.profilePage,
    url: ids.profilePage,
    name: "Matthew McCluster: résumé, work, recognition and identifiers",
    inLanguage: "en-US",
    dateModified: g.profileDateModified,
    isPartOf: { "@id": ids.website },
    mainEntity: { "@id": ids.person },
    about: { "@id": ids.person },
    breadcrumb: { "@id": ids.profilePage + "#breadcrumb" },
    primaryImageOfPage: { "@type": "ImageObject", url: g.person.image.url }
  };
  const credit = {
    "@type": "MusicRecording",
    "@id": ids.profilePage + "#sjw",
    name: "SJW",
    byArtist: { "@type": "MusicGroup", name: "A$hon Voyage", alternateName: "Ashon Voyage" },
    producer: { "@id": ids.person },
    url: "https://soundcloud.com/ashon_voyage/sjw-prod-matthew-mccluster"
  };
  const crumbs = {
    "@type": "BreadcrumbList",
    "@id": ids.profilePage + "#breadcrumb",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: g.base },
      { "@type": "ListItem", position: 2, name: "Matthew McCluster", item: ids.profilePage }
    ]
  };
  return {
    "@context": "https://schema.org",
    "@graph": [profile, g.website, g.person, ...g.organizations, ...g.platforms, credit, crumbs]
  };
}

export function renderBlock(g) {
  const json = JSON.stringify(buildGraph(g), null, 2)
    .split("\n").map((l) => "  " + l).join("\n");
  return `${START}\n  <script type="application/ld+json">\n${json}\n  </script>\n  ${END}`;
}

function main() {
  const g = JSON.parse(readFileSync(join(ROOT, "data/entity-graph.json"), "utf8"));
  const html = readFileSync(PAGE, "utf8");
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0) {
    console.error("matthew-mccluster.html has no entity-graph markers");
    process.exit(1);
  }
  const next = html.slice(0, a) + renderBlock(g) + html.slice(b + END.length);
  if (process.argv.includes("--check")) {
    if (next !== html) {
      console.error("matthew-mccluster.html JSON-LD drifted from data/entity-graph.json: run node tools/seo/build-entity-jsonld.mjs");
      process.exit(1);
    }
    console.log("entity graph: profile JSON-LD is current");
    return;
  }
  writeFileSync(PAGE, next);
  console.log("entity graph: wrote matthew-mccluster.html JSON-LD");
}

if (import.meta.url === `file://${process.argv[1]}`) main();
