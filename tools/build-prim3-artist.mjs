#!/usr/bin/env node
/* PRIM3, THE ARTIST: its page's track list and its graph, from the data.

     node tools/build-prim3-artist.mjs          # rewrite the blocks
     node tools/build-prim3-artist.mjs --check  # fail if they drifted

   Owner, 2026-11-02: "the album is actually called Cyber Security
   Specialist. ... the artist is PRIM3. PRIM3 needs their own artist page as
   that is its own artist. Separate entity from Matthew McCluster. But
   controlled by Matthew McCluster's account until it gets its own login."

   prim3-artist.html is that page. Its track list is the album as
   data/albums.json has it (slug prim3, the shelf the player plays), written
   as real HTML so a crawler that runs no script still reads it. Its graph
   is a WebPage about the act, the act itself (exactly the node
   data/seo/entity-graph.json -> music_acts.prim3 defines), the album and
   every recording, each by the act. Recording @ids are the catalogue's
   stable addresses (catalogue.html#<slug>); the album's is the catalogue
   graph's. No credit beyond the artist is claimed: none is known.

   Matthew McCluster is not in this graph as an artist. That his account
   manages the act is account control, not a schema.org fact, so it is
   stated on the page in words and recorded in
   data/seo/domain-architecture.json -> entities.prim3_artist. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { trackSlug, clock } from "./build-music-registry.mjs";
import { isoDuration } from "./build-catalogue.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://matthew.mccluster.org";
const PAGE = join(ROOT, "prim3-artist.html");
const URL = `${SITE}/prim3-artist.html`;
const ALBUM_SLUG = "prim3";
const MARK = {
  ld: ["<!-- prim3-artist-graph:start (generated by tools/build-prim3-artist.mjs; do not edit by hand) -->", "<!-- prim3-artist-graph:end -->"],
  tracks: ["<!-- prim3-artist-tracks:start (generated) -->", "<!-- prim3-artist-tracks:end -->"]
};

const esc = (s) => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;")
  .replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

export function album(albums) {
  const a = (albums.albums || []).find((x) => x.slug === ALBUM_SLUG);
  if (!a) throw new Error(`data/albums.json has no album ${ALBUM_SLUG}`);
  return a;
}

export function act(graph) {
  const node = graph.music_acts && graph.music_acts.prim3;
  if (!node) throw new Error("data/seo/entity-graph.json has no music_acts.prim3");
  return node;
}

export function trackRows(a) {
  return a.tracks.filter((t) => !t.gated).map((t) => {
    const href = `album.html?album=${ALBUM_SLUG}&t=${encodeURIComponent(t.title)}`;
    return `<li id="t-${esc(trackSlug(t))}"><a href="${esc(href)}" data-cta="prim3-artist-track">${esc(t.title)}</a><span>${esc(clock(t.seconds))}</span></li>`;
  }).join("\n        ");
}

export function buildGraph(a, node) {
  const ACT = { "@id": node["@id"] };
  const albumId = `${SITE}/catalogue.html#album-${ALBUM_SLUG}`;
  const tracks = a.tracks.filter((t) => !t.gated);
  const recordings = tracks.map((t) => JSON.parse(JSON.stringify({
    "@type": "MusicRecording",
    "@id": `${SITE}/catalogue.html#${trackSlug(t)}`,
    name: t.title,
    url: `${SITE}/album.html?album=${ALBUM_SLUG}&t=${encodeURIComponent(t.title)}`,
    duration: isoDuration(clock(t.seconds)),
    byArtist: ACT,
    inAlbum: { "@id": albumId }
  })));
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        /* a WebPage, not a ProfilePage: on this property a ProfilePage is
           always about the one Person (scripts/test/seo-contract.test.mjs) */
        "@type": "WebPage",
        "@id": `${URL}#page`,
        url: URL,
        name: "PRIM3, the artist",
        isPartOf: { "@id": `${SITE}/#website` },
        mainEntity: ACT,
        about: ACT
      },
      node,
      {
        "@type": "MusicAlbum",
        "@id": albumId,
        name: a.name,
        url: `${SITE}/album.html?album=${ALBUM_SLUG}`,
        image: `${SITE}/${a.art}`,
        byArtist: ACT,
        numTracks: recordings.length,
        track: { "@type": "ItemList", numberOfItems: recordings.length,
          itemListElement: recordings.map((r, i) => ({ "@type": "ListItem", position: i + 1, item: { "@id": r["@id"] } })) }
      },
      ...recordings
    ]
  };
}

function swap(html, [a, b], body, indent) {
  const i = html.indexOf(a), j = html.indexOf(b);
  if (i < 0 || j < 0) throw new Error(`prim3-artist.html is missing the marker ${a}`);
  return html.slice(0, i + a.length) + "\n" + body + "\n" + indent + html.slice(j);
}

export function render(html, albums, graph) {
  const a = album(albums);
  let next = swap(html, MARK.ld, `  <script type="application/ld+json">${JSON.stringify(buildGraph(a, act(graph)))}</script>`, "  ");
  next = swap(next, MARK.tracks, "        " + trackRows(a), "        ");
  const n = a.tracks.filter((t) => !t.gated).length;
  next = next.replace(/<span id="p3aCount">[^<]*<\/span>/, `<span id="p3aCount">${n} ${n === 1 ? "track" : "tracks"}</span>`);
  return next;
}

function main() {
  const albums = JSON.parse(readFileSync(join(ROOT, "data/albums.json"), "utf8"));
  const graph = JSON.parse(readFileSync(join(ROOT, "data/seo/entity-graph.json"), "utf8"));
  const html = readFileSync(PAGE, "utf8");
  const next = render(html, albums, graph);
  if (process.argv.includes("--check")) {
    if (next !== html) { console.error("prim3-artist.html drifted from data/albums.json or the entity graph: run node tools/build-prim3-artist.mjs"); process.exit(1); }
    console.log("prim3 artist page: current");
    return;
  }
  writeFileSync(PAGE, next);
  console.log(`prim3 artist page: wrote ${album(albums).tracks.length} tracks`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
